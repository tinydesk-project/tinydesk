/* The 16 rows of a character (bit 7 is the leftmost pixel), or NULL when
 * the font does not have it. */
const uint8_t *td_pyui_glyph(uint32_t cp)
{
    size_t lo = 0, hi = sizeof(s_glyphs) / sizeof(s_glyphs[0]);
    while (lo < hi)
    {
        size_t mid = (lo + hi) / 2;
        if (s_glyphs[mid].cp == cp)
            return s_glyphs[mid].rows;
        if (s_glyphs[mid].cp < cp)
            lo = mid + 1;
        else
            hi = mid;
    }
    return NULL;
}
