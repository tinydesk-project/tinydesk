#!/usr/bin/env python3
"""make_kbd_layouts.py - the keyboard layouts of the USB keyboard code.

Writes ports/esp_idf/app/usb_hid_layouts.h, the table usb_hid.c reads: per
layout 54 keys, the HID usages 0x04-0x38 (letters, digits, five control
keys, punctuation) and 0x64 (the key left of Z on ISO keyboards), each
with its character without Shift, with Shift and with AltGr. Dead keys
type their accent. To add a layout, add it below and run:

    python tools/make_kbd_layouts.py
"""
import os


LET = "abcdefghijklmnopqrstuvwxyz"


def row(letters, digits, punct, k64):
    keys = list(letters) + list(digits) + [""] * 5 + list(punct) + [k64]
    assert len(keys) == 54, len(keys)
    return keys


def alt(pairs):
    """AltGr: {position char on the US keyboard: character}."""
    keys = [""] * 54
    us = LET + "1234567890" + "\0" * 5 + "-=[]\\#;'`,./"
    for k, v in pairs.items():
        i = 53 if k == "<" else us.index(k)
        keys[i] = v
    return keys


def swap(letters, a, b):
    s = list(letters)
    ia, ib = LET.index(a), LET.index(b)
    s[ia], s[ib] = s[ib], s[ia]
    return "".join(s)


L = []
# board key value, name, plain, Shift, AltGr
L.append(("us", "US (English)",
          row(LET, "1234567890", ["-", "=", "[", "]", "\\", "#", ";", "'", "`", ",", ".", "/"], "\\"),
          row(LET.upper(), "!@#$%^&*()", ["_", "+", "{", "}", "|", "~", ":", '"', "~", "<", ">", "?"], "|"),
          [""] * 54))
L.append(("uk", "UK (English)",
          row(LET, "1234567890", ["-", "=", "[", "]", "#", "#", ";", "'", "`", ",", ".", "/"], "\\"),
          row(LET.upper(), ["!", '"', "£", "$", "%", "^", "&", "*", "(", ")"],
              ["_", "+", "{", "}", "~", "~", ":", "@", "¬", "<", ">", "?"], "|"),
          alt({"4": "€", "`": "¦"})))
de = swap(LET, "y", "z")
L.append(("de", "German",
          row(de, "1234567890", ["ß", "´", "ü", "+", "#", "#", "ö", "ä", "^", ",", ".", "-"], "<"),
          row(de.upper(), ["!", '"', "§", "$", "%", "&", "/", "(", ")", "="],
              ["?", "`", "Ü", "*", "'", "'", "Ö", "Ä", "°", ";", ":", "_"], ">"),
          alt({"q": "@", "e": "€", "m": "µ", "2": "²", "3": "³", "7": "{", "8": "[", "9": "]", "0": "}",
               "-": "\\", "]": "~", "<": "|"})))
fr = swap(swap(LET, "a", "q"), "w", "z")
fr = fr.replace("m", ",")              # the M key carries , ? on AZERTY
L.append(("fr", "French",
          row(fr, ["&", "é", '"', "'", "(", "-", "è", "_", "ç", "à"],
              [")", "=", "^", "$", "*", "*", "m", "ù", "²", ";", ":", "!"], "<"),
          row(fr.upper().replace(",", "?"), "1234567890",
              ["°", "+", "¨", "£", "µ", "µ", "M", "%", "", ".", "/", "§"], ">"),
          alt({"2": "~", "3": "#", "4": "{", "5": "[", "6": "|", "7": "`", "8": "\\", "9": "^", "0": "@",
               "-": "]", "=": "}", "e": "€"})))
L.append(("es", "Spanish",
          row(LET, "1234567890", ["'", "¡", "`", "+", "ç", "ç", "ñ", "´", "º", ",", ".", "-"], "<"),
          row(LET.upper(), ["!", '"', "·", "$", "%", "&", "/", "(", ")", "="],
              ["?", "¿", "^", "*", "Ç", "Ç", "Ñ", "¨", "ª", ";", ":", "_"], ">"),
          alt({"1": "|", "2": "@", "3": "#", "4": "~", "6": "¬", "e": "€", "[": "[", "]": "]", "'": "{",
               "\\": "}", "#": "}", "`": "\\"})))


def c_str(keys):
    """A C string, one UTF-8 character per key, \\001 for none; "" for no keys."""
    if not any(keys):
        return '""'
    out = '"'
    for k in keys:
        if not k:
            out += "\\001"
            continue
        assert len(k) == 1, k
        for b in k.encode("utf-8"):
            if b == 0x22:
                out += '\\"'
            elif b == 0x5C:
                out += "\\\\"
            elif 0x20 <= b < 0x7F:
                out += chr(b)
            else:
                out += "\\%03o" % b
    return out + '"'


OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ports", "esp_idf", "app", "usb_hid_layouts.h")
lines = ["/* usb_hid_layouts.h - generated by tools/make_kbd_layouts.py; do not edit. */",
         "static const usb_layout_t s_layouts[] = {"]
for code, name, p, s, a in L:
    for t in (p, s, a):
        assert len(t) == 54
    lines.append('    {"%s", "%s",' % (code, name))
    lines.append("     %s," % c_str(p))
    lines.append("     %s," % c_str(s))
    lines.append("     %s}," % c_str(a))
lines.append("};")
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", os.path.normpath(OUT))
