def load_psf1(path):
    data = gzip.open(path).read() if path.endswith(".gz") else open(path, "rb").read()
    if data[:2] != b"\x36\x04":
        sys.exit("not a PSF1 font: " + path)
    mode, height = data[2], data[3]
    if height != 16 or not mode & 2:
        sys.exit("need an 8x16 PSF1 font with a Unicode table")
    count = 512 if mode & 1 else 256
    glyphs = [data[4 + i * 16: 4 + (i + 1) * 16] for i in range(count)]
    table = data[4 + count * 16:]
    uni, pos = {}, 0
    for i in range(count):
        while True:
            (v,) = struct.unpack_from("<H", table, pos)
            pos += 2
            if v == 0xFFFF:
                break
            if v != 0xFFFE:
                uni.setdefault(v, glyphs[i])
    return uni


def rows(*pattern):
    """16 rows from strings of '#' and '.' (8 wide)."""
    assert len(pattern) == 16
    out = []
    for line in pattern:
        assert len(line) == 8, line
        out.append(sum(1 << (7 - i) for i, c in enumerate(line) if c == "#"))
    return bytes(out)


EXTRA = {
    0x2580: bytes([0xFF] * 8 + [0x00] * 8),                      # upper half block
    0x2584: bytes([0x00] * 8 + [0xFF] * 8),                      # lower half block
    0x258C: bytes([0xF0] * 16),                                  # left half block
    0x2590: bytes([0x0F] * 16),                                  # right half block
    0x2593: bytes([0xDD, 0x77] * 8),                             # dark shade
    0x25BA: rows("........", "........", "........", "#.......", "##......",
                 "###.....", "####....", "#####...", "######..", "#####...",
                 "####....", "###.....", "##......", "#.......", "........", "........"),
    0x25C4: rows("........", "........", "........", ".......#", "......##",
                 ".....###", "....####", "...#####", "..######", "...#####",
                 "....####", ".....###", "......##", ".......#", "........", "........"),
    0x263C: rows("........", "........", "...##...", "#..##..#", ".#....#.",
                 "..####..", ".##..##.", "##....##", ".##..##.", "..####..",
                 ".#....#.", "#..##..#", "...##...", "........", "........", "........"),
}


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    uni = load_psf1(sys.argv[1])
    for cp, g in EXTRA.items():
        uni.setdefault(cp, g)
    cps = sorted(c for c in uni if 0x20 <= c <= 0xFFFF and not 0x7F <= c < 0xA0)
    out = sys.stdout
    out.reconfigure(newline="\n")   # LF on Windows too
    out.write("/*\n * font8x16.c - the 8x16 font of the CrowPanel's LCD: %d characters,\n" % len(cps))
    out.write(" * sorted by code point. Generated by tools/make_lcd_font.py: do not edit.\n *\n")
    out.write(LICENCE + "\n *\n")
    out.write(" * The half blocks, the dark shade, U+25BA, U+25C4 and U+263C are drawn by\n")
    out.write(" * tools/make_lcd_font.py (TinyDesk, MIT licence).\n */\n")
    out.write('#include "font8x16.h"\n\n#include <stddef.h>\n\n')
    out.write("typedef struct\n{\n    uint16_t cp;\n    uint8_t rows[16];\n} glyph_t;\n\n")
    out.write("static const glyph_t s_glyphs[] = {\n")
    for c in cps:
        out.write("    {0x%04X, {%s}},\n" % (c, ", ".join("0x%02X" % b for b in uni[c])))
    out.write("};\n\n")
    out.write("const uint8_t *font8x16_glyph(uint16_t cp)\n{\n")
    out.write("    size_t lo = 0, hi = sizeof(s_glyphs) / sizeof(s_glyphs[0]);\n")
    out.write("    while (lo < hi)\n    {\n")
    out.write("        size_t mid = (lo + hi) / 2;\n")
    out.write("        if (s_glyphs[mid].cp == cp)\n            return s_glyphs[mid].rows;\n")
    out.write("        if (s_glyphs[mid].cp < cp)\n            lo = mid + 1;\n")
    out.write("        else\n            hi = mid;\n    }\n    return NULL;\n}\n")


if __name__ == "__main__":
    main()
