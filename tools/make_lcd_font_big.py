#!/usr/bin/env python3
"""Generate a larger font for the CrowPanel's LCD (ports/crowpanel7/main):
the cells of lcd.font = 20, 24 or 32.

    python tools/make_lcd_font_big.py Uni2-TerminusBold20x10.psf.gz Uni2-VGA16.psf.gz \\
        > ports/crowpanel7/main/font10x20.c

The glyphs come from Terminus Font (console-setup, /usr/share/consolefonts;
Copyright (c) 2010 Dimitar Toshkov Zhekov, SIL Open Font License 1.1: see
ports/crowpanel7/main/OFL-Terminus.txt), drawn natively at that size, so
large text stays smooth. The block elements (half blocks, quadrants, full
block), which the desktop's pixels are made of, are drawn here to fill the
cell exactly; the few characters of the 8x16 font (the second file) that
Terminus lacks are taken from it, scaled.
"""
import gzip
import struct
import sys

NOTICE = """\
 * Glyphs from Terminus Font (console-setup), Copyright (c) 2010 Dimitar
 * Toshkov Zhekov, under the SIL Open Font License 1.1 (OFL-Terminus.txt,
 * next to this file), with Reserved Font Name "Terminus Font"; this
 * modified version is not named so. The block elements are drawn by
 * tools/make_lcd_font_big.py; characters Terminus lacks come from the 8x16
 * font (font8x16.c), scaled."""


def load_psf(path):
    """{code point: (width, height, rows as lists of 0/1)}."""
    data = gzip.open(path).read() if path.endswith(".gz") else open(path, "rb").read()
    if data[:2] == b"\x36\x04":                      # PSF1: 8 wide
        mode, height = data[2], data[3]
        count = 512 if mode & 1 else 256
        width, size, start = 8, height, 4
        glyphs = [data[start + i * size: start + (i + 1) * size] for i in range(count)]
        table, pos, psf2 = data[start + count * size:], 0, False
    elif data[:4] == b"\x72\xb5\x4a\x86":            # PSF2
        _, hsize, flags, count, size, height, width = struct.unpack_from("<7I", data, 4)
        glyphs = [data[hsize + i * size: hsize + (i + 1) * size] for i in range(count)]
        table, pos, psf2 = data[hsize + count * size:], 0, True
    else:
        sys.exit("not a PSF font: " + path)
    bpr = (width + 7) // 8

    def bits(g):
        return [[(g[r * bpr + c // 8] >> (7 - c % 8)) & 1 for c in range(width)] for r in range(height)]

    uni = {}
    for i in range(count):
        if psf2:                                     # UTF-8 sequences, 0xFF ends a glyph's
            end = table.index(b"\xff", pos)
            entry, pos = table[pos:end], end + 1
            for part in entry.split(b"\xfe")[0:1]:   # single characters only
                for ch in part.decode("utf-8", "replace"):
                    uni.setdefault(ord(ch), bits(glyphs[i]))
        else:
            while True:
                (v,) = struct.unpack_from("<H", table, pos)
                pos += 2
                if v == 0xFFFF:
                    break
                if v != 0xFFFE:
                    uni.setdefault(v, bits(glyphs[i]))
    return width, height, uni


def block(w, h, cp):
    """The block elements, filling the w x h cell exactly."""
    hw, hh = w // 2, h // 2

    def quads(ul, ur, ll, lr):
        return [[(ul if x < hw else ur) if y < hh else (ll if x < hw else lr) for x in range(w)] for y in range(h)]

    table = {
        0x2580: (1, 1, 0, 0), 0x2584: (0, 0, 1, 1), 0x2588: (1, 1, 1, 1),
        0x258C: (1, 0, 1, 0), 0x2590: (0, 1, 0, 1),
        0x2596: (0, 0, 1, 0), 0x2597: (0, 0, 0, 1), 0x2598: (1, 0, 0, 0),
        0x2599: (1, 0, 1, 1), 0x259A: (1, 0, 0, 1), 0x259B: (1, 1, 1, 0),
        0x259C: (1, 1, 0, 1), 0x259D: (0, 1, 0, 0), 0x259E: (0, 1, 1, 0),
        0x259F: (0, 1, 1, 1),
    }
    return quads(*table[cp]) if cp in table else None


def scaled(g8, w, h):
    return [[g8[y * 16 // h][x * 8 // w] for x in range(w)] for y in range(h)]


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    w, h, uni = load_psf(sys.argv[1])
    _, _, vga = load_psf(sys.argv[2])
    for cp in [0x2580, 0x2584, 0x2588, 0x258C, 0x2590] + list(range(0x2596, 0x25A0)):
        uni[cp] = block(w, h, cp)
    for cp, g in vga.items():
        if cp not in uni:
            uni[cp] = scaled(g, w, h)
    cps = sorted(c for c in uni if 0x20 <= c <= 0xFFFF and not 0x7F <= c < 0xA0)
    bpr = (w + 7) // 8
    name = "font%dx%d" % (w, h)
    out = sys.stdout
    out.reconfigure(newline="\n")
    out.write("/*\n * %s.c - a %dx%d font of the CrowPanel's LCD (lcd.font = %d): %d\n" % (name, w, h, h, len(cps)))
    out.write(" * characters, sorted by code point. Generated by tools/make_lcd_font_big.py:\n")
    out.write(" * do not edit.\n *\n" + NOTICE + "\n */\n")
    out.write('#include "lcd_fonts.h"\n\n#include <stddef.h>\n\n')
    out.write("typedef struct\n{\n    uint16_t cp;\n    uint8_t rows[%d];\n} glyph_t;\n\n" % (h * bpr))
    out.write("static const glyph_t s_glyphs[] = {\n")
    for c in cps:
        g = uni[c]
        data = []
        for row in g:
            for b in range(bpr):
                data.append(sum(row[b * 8 + i] << (7 - i) for i in range(8) if b * 8 + i < w))
        out.write("    {0x%04X, {%s}},\n" % (c, ", ".join("0x%02X" % v for v in data)))
    out.write("};\n\n")
    out.write("const uint8_t *%s_glyph(uint16_t cp)\n{\n" % name)
    out.write("    size_t lo = 0, hi = sizeof(s_glyphs) / sizeof(s_glyphs[0]);\n")
    out.write("    while (lo < hi)\n    {\n")
    out.write("        size_t mid = (lo + hi) / 2;\n")
    out.write("        if (s_glyphs[mid].cp == cp)\n            return s_glyphs[mid].rows;\n")
    out.write("        if (s_glyphs[mid].cp < cp)\n            lo = mid + 1;\n")
    out.write("        else\n            hi = mid;\n    }\n    return NULL;\n}\n")


if __name__ == "__main__":
    main()
